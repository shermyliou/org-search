import { expect, test } from '@playwright/test';
import snapshot from '../data/mission2.json' with { type: 'json' };

test('real PiP supports searching, detail, tabs, notes and restoring the main page', async ({ page, context }) => {
  const org = snapshot.organizations[0];
  if (!org) throw new Error('Organization data is missing');
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  const opened = context.waitForEvent('page');
  await page.getByRole('button', { name: '浮動視窗' }).click();
  const pip = await opened;
  pip.on('pageerror', error => errors.push(error.message));
  await expect(page.locator('#pip-away')).toBeVisible();
  await expect(pip.locator('#search')).toBeVisible();
  await pip.getByRole('searchbox').fill(org.id);
  await pip.locator(`[data-org-id="${org.id}"]`).click();
  await expect(pip.locator('#detail-title')).toHaveText(org.name);
  await pip.getByRole('tab', { name: '其他資料' }).click();
  await expect(pip.getByRole('heading', { name: '組織主檔', exact: true })).toBeVisible();
  await pip.getByLabel('備註', { exact: true }).fill('PiP regression note');
  await expect(pip.locator('#note-status')).toHaveText('已儲存在此瀏覽器');
  await pip.getByRole('button', { name: '送出備註' }).click();
  await expect(pip.getByRole('tab', { name: '備註紀錄' })).toHaveAttribute('aria-selected', 'true');
  await expect(pip.locator('.note-message')).toContainText('PiP regression note');
  await expect(pip.getByRole('tab', { name: '備註紀錄' })).toHaveCSS('font-weight', '600');
  await expect.poll(() => pip.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await pip.close();
  await expect(page.locator('#detail-title')).toHaveText(org.name);
  await expect(page.locator('.note-message')).toContainText('PiP regression note');
  await expect(page.locator('#pip-away')).toBeHidden();
  await page.getByRole('button', { name: '返回搜尋結果' }).click();
  await expect(page.getByRole('searchbox')).toHaveValue(org.id);
  await expect(page.locator(`[data-org-id="${org.id}"]`)).toBeVisible();
  const reopened = context.waitForEvent('page');
  await page.getByRole('button', { name: '浮動視窗' }).click();
  const second = await reopened;
  await expect(second.getByRole('searchbox')).toHaveValue(org.id);
  await page.getByRole('button', { name: '返回此分頁' }).click();
  await expect(page.getByRole('searchbox')).toBeVisible();
  expect(errors).toEqual([]);
});
